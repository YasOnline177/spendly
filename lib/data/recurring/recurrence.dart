  import 'dart:math';

enum Frequency { weekly, monthly }

DateTime dateOnly(DateTime d) => DateTime(d.year, d.month, d.day);

/// The date of occurrence number [index] (0 is the start date itself).
///
/// Monthly rules keep the start day, but months that are too short use their
/// last day (31st becomes Feb 28/29, Apr 30) without drifting afterwards.
DateTime occurrenceAt(Frequency frequency, DateTime start, int index) {
  final s = dateOnly(start);
  switch (frequency) {
    case Frequency.weekly:
      return DateTime(s.year, s.month, s.day + 7 * index);
    case Frequency.monthly:
      final firstOfMonth = DateTime(s.year, s.month + index);
      final lastDay =
          DateTime(firstOfMonth.year, firstOfMonth.month + 1, 0).day;
      return DateTime(
        firstOfMonth.year,
        firstOfMonth.month,
        min(s.day, lastDay),
      );
  }
}

/// Every occurrence from [start] up to and including [until] (dates only).
/// [maxCount] is a safety net against runaway loops.
List<DateTime> occurrencesUpTo(
  Frequency frequency,
  DateTime start,
  DateTime until, {
  int maxCount = 1000,
}) {
  final end = dateOnly(until);
  final result = <DateTime>[];
  for (var i = 0; i < maxCount; i++) {
    final date = occurrenceAt(frequency, start, i);
    if (date.isAfter(end)) break;
    result.add(date);
  }
  return result;
}

/// The first occurrence strictly after [after].
DateTime nextOccurrence(Frequency frequency, DateTime start, DateTime after) {
  final limit = dateOnly(after);
  for (var i = 0;; i++) {
    final date = occurrenceAt(frequency, start, i);
    if (date.isAfter(limit)) return date;
  }
}

/// The id of the transaction generated by [ruleSyncId] for [date].
/// Deterministic on purpose: every device derives the same id.
String occurrenceSyncId(String ruleSyncId, DateTime date) {
  final y = date.year.toString().padLeft(4, '0');
  final m = date.month.toString().padLeft(2, '0');
  final d = date.day.toString().padLeft(2, '0');
  return '$ruleSyncId:$y$m$d';
}